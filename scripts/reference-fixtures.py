"""Generate synthetic fixtures with an external, pinned mymc+ checkout.

Usage: python3 scripts/reference-fixtures.py /path/to/mymcplus
This script uses the independent tool through its API. No mymc+ code is bundled.
"""
import gzip
import hashlib
import io
import json
from pathlib import Path
import subprocess
import sys

REVISION = "5e58891fd036d9f39a6c3076f998514c8f1cb8f9"
checkout = Path(sys.argv[1]).resolve()
actual = subprocess.check_output(["git", "-C", str(checkout), "rev-parse", "HEAD"], text=True).strip()
if actual != REVISION:
    raise SystemExit(f"Expected mymc+ {REVISION}, got {actual}")
sys.path.insert(0, str(checkout))
from mymcplus import ps2mc  # noqa: E402

# Stable dates in the external formatter, independent of local time and timezone.
ps2mc.tod_now = lambda: (6, 5, 4, 3, 2, 2001)
target = Path(__file__).resolve().parent.parent / "tests" / "fixtures"
target.mkdir(parents=True, exist_ok=True)


def payload(size, salt):
    return bytes((i * 31 + i // 251 + salt) % 256 for i in range(size))


def write(card, path, data, mode="wb"):
    f = card.open(path, mode)
    if mode == "r+b":
        f.seek(0, 2)
    f.write(data)
    f.close()


def inventory(card):
    result = {}

    def visit(path):
        directory = card.dir_open(path)
        children = [directory[i] for i in range(2, len(directory))]
        directory.close()
        for entry in children:
            if not entry[0] & 0x8000:
                continue
            name = entry[8].decode("ascii")
            full = path.rstrip("/") + "/" + name
            item = {"mode": entry[0], "length": entry[2], "created": entry[3],
                    "modified": entry[6], "attributes": entry[7]}
            if entry[0] & 0x20:
                item["kind"] = "directory"
                result[full] = item
                visit(full)
            else:
                f = card.open(full, "rb")
                data = f.read()
                f.close()
                item.update(kind="file", sha256=hashlib.sha256(data).hexdigest())
                result[full] = item
    visit("/")
    return result


manifest = {"producer": "mymc+", "repository": "https://git.sr.ht/~thestr4ng3r/mymcplus",
            "revision": REVISION, "data": "Synthetic bytes only, generated by reference-fixtures.py", "cards": {}}
for role in ("source", "destination"):
    for ecc in (False, True):
        stream = io.BytesIO()
        card = ps2mc.ps2mc(stream, params=(True, 512, 16, 16384))
        if role == "source":
            card.mkdir("/SAVE-A")
            # Append after another allocation to force a fragmented chain.
            write(card, "/SAVE-A/fragmented", payload(1024, 17))
            write(card, "/SAVE-A/separator", payload(1024, 33))
            write(card, "/SAVE-A/fragmented", payload(300001, 99), "r+b")
            for size in (0, 1, 511, 512, 513, 1023, 1024, 1025):
                write(card, f"/SAVE-A/bytes-{size}", payload(size, size % 256))
            card.mkdir("/SAVE-A/NESTED")
            write(card, "/SAVE-A/NESTED/12345678901234567890123456789012", payload(2500, 91))
            entry = card.get_dirent("/SAVE-A/bytes-513")
            entry[0] |= 0x2008  # Hidden and copy protected. Preserve both.
            entry[7] = 0x12345678
            card.set_dirent("/SAVE-A/bytes-513", entry)
        else:
            card.mkdir("/KEEP")
            write(card, "/KEEP/original", payload(1701, 65))
            card.mkdir("/ALSO-KEEP")  # Four root slots force expansion when copying.
        card.flush()
        assert card.check(), "Independent fixture check failed"
        entries = inventory(card)
        data = stream.getvalue()
        # Format with ECC, then strip spare areas for the data-only fixture.
        # The pinned tool's data-only formatter retains a 528-byte backup offset
        # and extends the file past 8 MiB. Do not make that defect our baseline.
        if not ecc:
            data = b"".join(data[i:i + 512] for i in range(0, len(data), 528))
        filename = f"{role}-{'ecc' if ecc else 'data'}.ps2.gz"
        (target / filename).write_bytes(gzip.compress(data, mtime=0))
        manifest["cards"][filename] = {"layout": "ecc" if ecc else "data", "bytes": len(data),
                                      "sha256": hashlib.sha256(data).hexdigest(), "entries": entries}
        card.close()
(target / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
print("Generated four independently checked synthetic fixtures.")
